#!/usr/bin/env python3
"""
G1 29-DoF locomotion policy (trained with unitree_rl_lab) with ROS 2 bridge.
Loads trained policy, subscribes to /cmd_vel, publishes /joint_states and /odom.

This is the unitree_rl_lab counterpart of g1_policy_ros2.py. That script runs policies
trained on Isaac Lab's stock G1 task (g1_minimal.usd, 37 joints, 123-dim obs). Policies from
unitree_rl_lab's Unitree-G1-29dof-Velocity task use a different robot and a different
observation layout, so they need this script instead:
  - robot: g1_29dof_rev_1_0.urdf from unitree_ros (29 joints), imported exactly like in
    training via unitree_rl_lab's UNITREE_G1_29DOF_CFG
  - obs:   96 dims per frame x 5 frames of history = 480 dims, no base_lin_vel
  - action scale 0.25 (stock G1 task: 0.5)

Run with:
    G1_POLICY_PATH=/path/to/exported/policy.pt \\
        common/launch_isaac_ros2_unitree.sh g1/g1_29dof_policy_ros2.py

Env vars (all have defaults for a standard Isaac Sim 5.1 + env_isaaclab install):
    ISAACLAB_VENV   - path to the Isaac Sim python venv (default: ~/env_isaaclab)
    ISAACLAB_PATH   - path to the IsaacLab repo checkout (default: ~/IsaacLab)
    ISAAC_PYTHON    - python version of that venv, e.g. python3.11 (default: python3.11)
    G1_POLICY_PATH  - required: path to the exported TorchScript policy (exported/policy.pt,
                      auto-generated by unitree_rl_lab's play.py alongside the checkpoints)
"""

import os
import sys

ISAACLAB_VENV = os.path.expanduser(os.environ.get("ISAACLAB_VENV", "~/env_isaaclab"))
ISAACLAB_PATH = os.path.expanduser(os.environ.get("ISAACLAB_PATH", "~/IsaacLab"))
ISAAC_PYTHON = os.environ.get("ISAAC_PYTHON", "python3.11")

POLICY_PATH = os.environ.get("G1_POLICY_PATH")
if not POLICY_PATH:
    raise RuntimeError(
        "Set G1_POLICY_PATH to an exported TorchScript policy, e.g.:\n"
        "  export G1_POLICY_PATH=~/unitree_g1/unitree_rl_lab/logs/rsl_rl/unitree_g1_29dof_velocity/<timestamp>/exported/policy.pt\n"
        "Run unitree_rl_lab's scripts/rsl_rl/play.py once to produce it."
    )
POLICY_PATH = os.path.expanduser(POLICY_PATH)

# ROS 2 bridge env vars - must be set before SimulationApp
os.environ["ROS_DISTRO"] = "humble"
os.environ["RMW_IMPLEMENTATION"] = "rmw_fastrtps_cpp"
os.environ["LD_LIBRARY_PATH"] = os.environ.get("LD_LIBRARY_PATH", "") + \
    f":{ISAACLAB_VENV}/lib/{ISAAC_PYTHON}/site-packages/isaacsim/exts/isaacsim.ros2.bridge/humble/lib"
os.environ.pop("AMENT_PREFIX_PATH", None)

# Add Isaac Lab to path
sys.path.insert(0, f"{ISAACLAB_PATH}/source/isaaclab")
sys.path.insert(0, f"{ISAACLAB_PATH}/source/isaaclab_tasks")

from isaacsim import SimulationApp
# Start with Isaac Lab's app config (same one train.py/play.py use) instead of the plain Isaac
# Sim one: Isaac Lab's URDF converter needs the URDF importer version that config pins
# (isaacsim.asset.importer.urdf-2.4.31); the plain config loads an older, incompatible one.
app = SimulationApp({"headless": False}, experience=f"{ISAACLAB_PATH}/apps/isaaclab.python.kit")

import numpy as np
from collections import deque
from scipy.spatial.transform import Rotation as R
import omni
import omni.graph.core as og
import usdrt.Sdf
# Same classes as omni.isaac.core.* in g1_policy_ros2.py; that deprecated alias isn't
# loaded by Isaac Lab's app config, so use the current isaacsim.core names.
from isaacsim.core.api import World
from isaacsim.core.utils.extensions import enable_extension
from pxr import Usd, UsdPhysics


enable_extension("isaacsim.ros2.bridge")

import torch

# ── Load trained policy ─────────────────────────────────────────────────────────
# TorchScript module auto-exported by unitree_rl_lab's play.py (exported/policy.pt).
policy = torch.jit.load(POLICY_PATH, map_location="cpu")
policy.eval()
print("Policy loaded from:", POLICY_PATH)

# ── Scene setup ────────────────────────────────────────────────────────────────
# physics_dt matches training (params/env.yaml: sim.dt=0.005, decimation=4 -> 50 Hz
# control). rendering_dt is set equal to physics_dt so every world.step() advances
# exactly one 0.005s tick (see g1_policy_ros2.py for the full explanation).
world = World(stage_units_in_meters=1.0, physics_dt=1.0 / 200.0, rendering_dt=1.0 / 200.0)
# Training terrain material: static/dynamic friction 1.0, restitution 0 (params/env.yaml).
world.scene.add_default_ground_plane(static_friction=1.0, dynamic_friction=1.0, restitution=0.0)

# Spawn the robot with the exact same spawn config as training: unitree_rl_lab's
# UnitreeUrdfFileCfg converts g1_29dof_rev_1_0.urdf (from UNITREE_ROS_DIR, set in
# unitree_rl_lab/assets/robots/unitree.py) to USD with the same importer settings
# (zero drive gains, capsule collisions, self-collisions, solver iterations, ...).
from unitree_rl_lab.assets.robots.unitree import UNITREE_G1_29DOF_CFG

G1_PRIM = "/World/G1"  # top-level prim, used for placing the whole asset
spawn_cfg = UNITREE_G1_29DOF_CFG.spawn
spawn_cfg.func(G1_PRIM, spawn_cfg, translation=(0.0, 0.0, 0.8))  # matches training init_state z=0.8

# The articulation root of the URDF-converted USD isn't necessarily the top-level
# prim, so find it instead of hard-coding it (unlike g1_policy_ros2.py's "pelvis").
stage = omni.usd.get_context().get_stage()
G1_ROOT_PRIM = None
for p in Usd.PrimRange(stage.GetPrimAtPath(G1_PRIM)):
    if p.HasAPI(UsdPhysics.ArticulationRootAPI):
        G1_ROOT_PRIM = str(p.GetPath())
        break
if G1_ROOT_PRIM is None:
    raise RuntimeError(f"No ArticulationRootAPI found under {G1_PRIM} - URDF import failed?")
print("Articulation root:", G1_ROOT_PRIM)

# ── ROS 2 OmniGraph bridge ─────────────────────────────────────────────────────
og.Controller.edit(
    {"graph_path": "/ActionGraph", "evaluator_name": "execution"},
    {
        og.Controller.Keys.CREATE_NODES: [
            ("OnPlaybackTick",    "omni.graph.action.OnPlaybackTick"),
            ("ROS2Context",       "isaacsim.ros2.bridge.ROS2Context"),
            ("PublishJointState", "isaacsim.ros2.bridge.ROS2PublishJointState"),
            ("SubscribeTwist",    "isaacsim.ros2.bridge.ROS2SubscribeTwist"),
            ("ComputeOdometry",   "isaacsim.core.nodes.IsaacComputeOdometry"),
            ("ReadSimTime",       "isaacsim.core.nodes.IsaacReadSimulationTime"),
            ("PublishOdometry",   "isaacsim.ros2.bridge.ROS2PublishOdometry"),
        ],
        og.Controller.Keys.CONNECT: [
            ("OnPlaybackTick.outputs:tick",        "PublishJointState.inputs:execIn"),
            ("OnPlaybackTick.outputs:tick",        "SubscribeTwist.inputs:execIn"),
            ("OnPlaybackTick.outputs:tick",        "ComputeOdometry.inputs:execIn"),
            ("ROS2Context.outputs:context",        "PublishJointState.inputs:context"),
            ("ROS2Context.outputs:context",        "SubscribeTwist.inputs:context"),
            ("ROS2Context.outputs:context",        "PublishOdometry.inputs:context"),
            ("ComputeOdometry.outputs:execOut",         "PublishOdometry.inputs:execIn"),
            ("ComputeOdometry.outputs:position",        "PublishOdometry.inputs:position"),
            ("ComputeOdometry.outputs:orientation",     "PublishOdometry.inputs:orientation"),
            ("ComputeOdometry.outputs:linearVelocity",  "PublishOdometry.inputs:linearVelocity"),
            ("ComputeOdometry.outputs:angularVelocity", "PublishOdometry.inputs:angularVelocity"),
            ("ReadSimTime.outputs:simulationTime",      "PublishOdometry.inputs:timeStamp"),
        ],
        og.Controller.Keys.SET_VALUES: [
            ("PublishJointState.inputs:targetPrim", [G1_ROOT_PRIM]),
            ("PublishJointState.inputs:topicName",  "joint_states"),
            ("SubscribeTwist.inputs:topicName",     "cmd_vel"),
            ("ComputeOdometry.inputs:chassisPrim",  [usdrt.Sdf.Path(G1_ROOT_PRIM)]),
            ("PublishOdometry.inputs:topicName",    "odom"),
        ],
    },
)

world.reset()

# ── Articulation handle ────────────────────────────────────────────────────────
from isaacsim.core.prims import SingleArticulation
robot = SingleArticulation(prim_path=G1_ROOT_PRIM, name="g1")
try:
    robot.initialize()
except Exception as e:
    raise RuntimeError(f"Failed to initialize articulation at {G1_ROOT_PRIM}.") from e

# The URDF is imported with zero drive stiffness/damping (UnitreeUrdfFileCfg.joint_drive),
# but switch to effort control explicitly anyway so no native drive fights our PD torque
# (see g1_policy_ros2.py for why this matters).
robot._articulation_view.switch_control_mode("effort")

try:
    usd_joint_names = list(robot.joint_names)
except AttributeError:
    usd_joint_names = list(robot.dof_names)
print(f"USD joint order ({len(usd_joint_names)} joints):", usd_joint_names)

# ── Training joint order ────────────────────────────────────────────────────────
# Order of the joints in the policy's obs/action vectors (Isaac Lab's articulation order
# in training). Derived from params/deploy.yaml: joint_ids_map maps this order onto the
# Unitree SDK order (UNITREE_G1_29DOF_CFG.joint_sdk_names). Everything below is built in
# this order, and SIM_TO_TRAIN/TRAIN_TO_SIM convert from/to whatever order the sim reports,
# so this stays correct even if the importer orders the joints differently.
TRAIN_JOINT_ORDER = [
    "left_hip_pitch_joint",     "right_hip_pitch_joint",     "waist_yaw_joint",
    "left_hip_roll_joint",      "right_hip_roll_joint",      "waist_roll_joint",
    "left_hip_yaw_joint",       "right_hip_yaw_joint",       "waist_pitch_joint",
    "left_knee_joint",          "right_knee_joint",
    "left_shoulder_pitch_joint", "right_shoulder_pitch_joint",
    "left_ankle_pitch_joint",   "right_ankle_pitch_joint",
    "left_shoulder_roll_joint", "right_shoulder_roll_joint",
    "left_ankle_roll_joint",    "right_ankle_roll_joint",
    "left_shoulder_yaw_joint",  "right_shoulder_yaw_joint",
    "left_elbow_joint",         "right_elbow_joint",
    "left_wrist_roll_joint",    "right_wrist_roll_joint",
    "left_wrist_pitch_joint",   "right_wrist_pitch_joint",
    "left_wrist_yaw_joint",     "right_wrist_yaw_joint",
]

missing = sorted(set(usd_joint_names) ^ set(TRAIN_JOINT_ORDER))
if missing:
    raise RuntimeError(f"Sim joints and TRAIN_JOINT_ORDER differ (G1 variant mismatch?): {missing}")

# sim_vec[SIM_TO_TRAIN] -> training order;  train_vec[TRAIN_TO_SIM] -> sim order
SIM_TO_TRAIN = np.array([usd_joint_names.index(n) for n in TRAIN_JOINT_ORDER])
TRAIN_TO_SIM = np.array([TRAIN_JOINT_ORDER.index(n) for n in usd_joint_names])

# ── Per-joint defaults, PD gains, and effort limits ─────────────────────────────
# Matches UNITREE_G1_29DOF_CFG's actuator groups (N7520-14.3, N7520-22.5, N5020-16,
# W4010-25) and init_state in unitree_rl_lab/assets/robots/unitree.py, cross-checked
# against params/deploy.yaml (stiffness/damping/default_joint_pos) for this run.
# All actuators have armature=0.01, set on the articulation below.
#   name: (default_pos [rad], stiffness/KP, damping/KD, effort_limit [N*m])
JOINT_GAINS = {
    # N7520-14.3
    "left_hip_pitch_joint":       (-0.10, 100.0, 2.0,  88.0),
    "right_hip_pitch_joint":      (-0.10, 100.0, 2.0,  88.0),
    "left_hip_yaw_joint":         ( 0.0,  100.0, 2.0,  88.0),
    "right_hip_yaw_joint":        ( 0.0,  100.0, 2.0,  88.0),
    "waist_yaw_joint":            ( 0.0,  200.0, 5.0,  88.0),
    # N7520-22.5
    "left_hip_roll_joint":        ( 0.0,  100.0, 2.0, 139.0),
    "right_hip_roll_joint":       ( 0.0,  100.0, 2.0, 139.0),
    "left_knee_joint":            ( 0.30, 150.0, 4.0, 139.0),
    "right_knee_joint":           ( 0.30, 150.0, 4.0, 139.0),
    # N5020-16
    "left_ankle_pitch_joint":     (-0.20,  40.0, 2.0,  25.0),
    "right_ankle_pitch_joint":    (-0.20,  40.0, 2.0,  25.0),
    "left_ankle_roll_joint":      ( 0.0,   40.0, 2.0,  25.0),
    "right_ankle_roll_joint":     ( 0.0,   40.0, 2.0,  25.0),
    "waist_roll_joint":           ( 0.0,   40.0, 5.0,  25.0),
    "waist_pitch_joint":          ( 0.0,   40.0, 5.0,  25.0),
    "left_shoulder_pitch_joint":  ( 0.30,  40.0, 1.0,  25.0),
    "right_shoulder_pitch_joint": ( 0.30,  40.0, 1.0,  25.0),
    "left_shoulder_roll_joint":   ( 0.25,  40.0, 1.0,  25.0),
    "right_shoulder_roll_joint":  (-0.25,  40.0, 1.0,  25.0),
    "left_shoulder_yaw_joint":    ( 0.0,   40.0, 1.0,  25.0),
    "right_shoulder_yaw_joint":   ( 0.0,   40.0, 1.0,  25.0),
    "left_elbow_joint":           ( 0.97,  40.0, 1.0,  25.0),
    "right_elbow_joint":          ( 0.97,  40.0, 1.0,  25.0),
    "left_wrist_roll_joint":      ( 0.15,  40.0, 1.0,  25.0),
    "right_wrist_roll_joint":     (-0.15,  40.0, 1.0,  25.0),
    # W4010-25
    "left_wrist_pitch_joint":     ( 0.0,   40.0, 1.0,   5.0),
    "right_wrist_pitch_joint":    ( 0.0,   40.0, 1.0,   5.0),
    "left_wrist_yaw_joint":       ( 0.0,   40.0, 1.0,   5.0),
    "right_wrist_yaw_joint":      ( 0.0,   40.0, 1.0,   5.0),
}
ARMATURE = 0.01

NUM_JOINTS = len(TRAIN_JOINT_ORDER)
# Training-order vectors (used for obs/actions)
DEFAULT_POS = np.array([JOINT_GAINS[n][0] for n in TRAIN_JOINT_ORDER])
# Sim-order vectors (used for the PD torque loop, which talks to the sim directly)
DEFAULT_POS_SIM = DEFAULT_POS[TRAIN_TO_SIM]
KP_VEC = np.array([JOINT_GAINS[n][1] for n in usd_joint_names])
KD_VEC = np.array([JOINT_GAINS[n][2] for n in usd_joint_names])
EFFORT_LIMIT_VEC = np.array([JOINT_GAINS[n][3] for n in usd_joint_names])

# Armature matters here: without it the light wrist links are too stiff for the
# explicit PD loop at 200 Hz and oscillate.
robot._articulation_view.set_armatures(np.full((1, NUM_JOINTS), ARMATURE))
robot._articulation_view.set_max_efforts(EFFORT_LIMIT_VEC[None, :])

# Start in the training default pose (the URDF import has every joint at 0).
robot.set_joint_positions(DEFAULT_POS_SIM)
robot.set_joint_velocities(np.zeros(NUM_JOINTS))

# ── Observation history ─────────────────────────────────────────────────────────
# unitree_rl_lab uses history_length=5 on the policy obs group. Isaac Lab keeps a
# separate history per term (oldest -> newest), flattens each term, then concatenates
# the terms, so the 480-dim obs is laid out as:
#   [ang_vel x5 | gravity x5 | cmd x5 | joint_pos x5 | joint_vel x5 | last_action x5]
# not as 5 stacked 96-dim frames. On the first step the history is filled with copies
# of the first frame (Isaac Lab's CircularBuffer does the same after a reset).
HISTORY_LEN = 5
OBS_TERMS = ["base_ang_vel", "projected_gravity", "velocity_commands",
             "joint_pos_rel", "joint_vel_rel", "last_action"]
obs_history = {name: deque(maxlen=HISTORY_LEN) for name in OBS_TERMS}


def push_obs(terms):
    for name in OBS_TERMS:
        if len(obs_history[name]) == 0:
            obs_history[name].extend([terms[name]] * HISTORY_LEN)
        else:
            obs_history[name].append(terms[name])
    return np.concatenate([np.concatenate(list(obs_history[name])) for name in OBS_TERMS])


last_action = torch.zeros(NUM_JOINTS)
cmd_vel = [0.0, 0.0, 0.0]  # [vx, vy, yaw_rate]

# ── ROS 2 cmd_vel reader ───────────────────────────────────────────────────────
def get_cmd_vel():
    """Read the latest cmd_vel from the OmniGraph SubscribeTwist node."""
    try:
        linear = og.Controller.get(og.Controller.attribute("/ActionGraph/SubscribeTwist.outputs:linearVelocity"))
        angular_z = og.Controller.get(og.Controller.attribute("/ActionGraph/SubscribeTwist.outputs:angularVelocity"))[2]
        return [float(linear[0]), float(linear[1]), float(angular_z)]
    except Exception:
        return [0.0, 0.0, 0.0]

# ── PD torque control (replicates the per-group ImplicitActuator model) ─────────
# Torque is recomputed from fresh joint state and reapplied every physics step (not
# just every policy step), like the actuator model in training.
# Target joint positions (sim order), held fixed between policy updates.
target_pos = DEFAULT_POS_SIM.copy()

# ── Main loop ──────────────────────────────────────────────────────────────────
world.play()
print("Simulation running. Topics: /joint_states, /odom, /cmd_vel")
print("Trained command ranges: vx [-0.5, 1.0], vy [-0.3, 0.3], yaw [-0.2, 0.2] (params/deploy.yaml)")

step = 0
POLICY_FREQ = 4  # run policy every 4 sim steps (matches decimation=4)

while app.is_running():
    # Apply PD torque every physics step, toward the current held-fixed target.
    joint_pos_raw = robot.get_joint_positions()
    joint_vel_raw = robot.get_joint_velocities()
    if joint_pos_raw is not None and joint_vel_raw is not None:
        effort = KP_VEC * (target_pos - joint_pos_raw) - KD_VEC * joint_vel_raw
        effort = np.clip(effort, -EFFORT_LIMIT_VEC, EFFORT_LIMIT_VEC)
        robot.set_joint_efforts(effort)

    # Only render on the last physics tick of each decimation window (~50 fps).
    world.step(render=(step + 1) % POLICY_FREQ == 0)
    step += 1

    if step % POLICY_FREQ != 0:
        continue

    # Read cmd_vel from ROS 2
    cmd = get_cmd_vel()

    # Get robot state
    pos, orient = robot.get_world_pose()
    ang_vel_world = robot.get_angular_velocity()
    joint_pos_raw = robot.get_joint_positions()
    joint_vel_raw = robot.get_joint_velocities()

    if joint_pos_raw is None or joint_vel_raw is None:
        continue

    # Isaac Sim / Isaac Lab use (w, x, y, z) quaternion convention.
    # scipy.spatial.transform.Rotation.from_quat expects (x, y, z, w).
    quat = orient  # (w, x, y, z) from Isaac Sim
    rot = R.from_quat([quat[1], quat[2], quat[3], quat[0]])  # → (x, y, z, w) for scipy

    # Rotate world-frame angular velocity to body frame (matches training obs: root_ang_vel_b)
    ang_vel_body = rot.inv().apply(ang_vel_world)

    # Gravity projected into body frame
    gravity_world = np.array([0.0, 0.0, -1.0])
    projected_gravity = rot.inv().apply(gravity_world)

    # One frame of observation terms (96 dims), in training joint order, with the
    # per-term scales from params/env.yaml applied before they enter the history.
    obs = push_obs({
        "base_ang_vel":      ang_vel_body * 0.2,                              # 3
        "projected_gravity": projected_gravity,                               # 3
        "velocity_commands": np.array(cmd),                                   # 3
        "joint_pos_rel":     joint_pos_raw[SIM_TO_TRAIN] - DEFAULT_POS,       # 29
        "joint_vel_rel":     joint_vel_raw[SIM_TO_TRAIN] * 0.05,              # 29
        "last_action":       last_action.numpy(),                             # 29
    })  # -> 480 dims with history

    # Run policy (JIT module: obs -> action mean, no extra outputs)
    with torch.no_grad():
        obs_tensor = torch.from_numpy(obs).float().unsqueeze(0)
        action = policy(obs_tensor).squeeze(0)

    last_action = action.clone()

    if step % (POLICY_FREQ * 50) == 0:  # print every ~50 policy steps
        print(f"[step {step}] obs norm: {np.linalg.norm(obs):.3f} | action norm: {action.norm():.3f}")

    # scale=0.25, offset=default pose (params/deploy.yaml: actions.JointPositionAction)
    target_pos = (DEFAULT_POS + action.numpy() * 0.25)[TRAIN_TO_SIM]

app.close()
