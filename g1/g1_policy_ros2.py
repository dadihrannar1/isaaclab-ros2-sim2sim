#!/usr/bin/env python3
"""
G1 locomotion policy with ROS 2 bridge.
Loads trained policy, subscribes to /cmd_vel, publishes /joint_states and /odom.

Run with:
    G1_POLICY_PATH=/path/to/exported/policy.pt \\
        common/launch_isaac_ros2.sh g1/g1_policy_ros2.py

Env vars (all have defaults for a standard Isaac Sim 5.1 + env_isaaclab install):
    ISAACLAB_VENV   - path to the Isaac Sim python venv (default: ~/env_isaaclab)
    ISAACLAB_PATH   - path to the IsaacLab repo checkout (default: ~/IsaacLab)
    ISAAC_PYTHON    - python version of that venv, e.g. python3.11 (default: python3.11)
    G1_POLICY_PATH  - required: path to the exported TorchScript policy (exported/policy.pt,
                      auto-generated by rsl_rl's play.py alongside the checkpoints)
"""

import os
import sys

ISAACLAB_VENV = os.path.expanduser(os.environ.get("ISAACLAB_VENV", "~/env_isaaclab"))
ISAACLAB_PATH = os.path.expanduser(os.environ.get("ISAACLAB_PATH", "~/IsaacLab"))
ISAAC_PYTHON = os.environ.get("ISAAC_PYTHON", "python3.11")

POLICY_PATH = os.environ.get("G1_POLICY_PATH")
if not POLICY_PATH:
    raise RuntimeError(
        "Set G1_POLICY_PATH to an exported TorchScript policy, e.g.:\n"
        "  export G1_POLICY_PATH=~/IsaacLab/logs/rsl_rl/g1_flat/<timestamp>/exported/policy.pt\n"
        "See the README for the train.py/play.py commands to produce one."
    )
POLICY_PATH = os.path.expanduser(POLICY_PATH)

# ROS 2 bridge env vars - must be set before SimulationApp
os.environ["ROS_DISTRO"] = "humble"
os.environ["RMW_IMPLEMENTATION"] = "rmw_fastrtps_cpp"
os.environ["LD_LIBRARY_PATH"] = os.environ.get("LD_LIBRARY_PATH", "") + \
    f":{ISAACLAB_VENV}/lib/{ISAAC_PYTHON}/site-packages/isaacsim/exts/isaacsim.ros2.bridge/humble/lib"
os.environ.pop("AMENT_PREFIX_PATH", None)

# Add Isaac Lab to path
sys.path.insert(0, f"{ISAACLAB_PATH}/source/isaaclab")
sys.path.insert(0, f"{ISAACLAB_PATH}/source/isaaclab_tasks")

from isaacsim import SimulationApp
app = SimulationApp({"headless": False})

import numpy as np
from scipy.spatial.transform import Rotation as R
import io
import omni
import omni.graph.core as og
import usdrt.Sdf
from omni.isaac.core import World
from omni.isaac.core.utils.extensions import enable_extension
from isaacsim.core.utils.stage import add_reference_to_stage
from pxr import UsdGeom, Gf


enable_extension("isaacsim.ros2.bridge")

import torch

# ── Load trained policy ─────────────────────────────────────────────────────────
# Using the TorchScript module that Isaac Lab's rsl_rl play.py auto-exports,
# instead of hand-rebuilding the actor network (as a1_policy_ros2.py had to):
# it bakes in the exact trained architecture and weights, so there's no risk of
# guessing hidden-layer sizes/activation wrong.
policy = torch.jit.load(POLICY_PATH, map_location="cpu")
policy.eval()
print("Policy loaded from:", POLICY_PATH)

# ── Scene setup ────────────────────────────────────────────────────────────────
# physics_dt matches training (params/env.yaml: sim.dt=0.005, decimation=4 -> 50 Hz
# control). rendering_dt is set equal to physics_dt: when they differ,
# world.step(render=True) runs int(rendering_dt/physics_dt) physics substeps per
# call instead of exactly one (see SimulationContext.step()), which breaks the
# "reapply torque every physics tick" loop below. Keeping them equal makes every
# world.step() call advance exactly one deterministic 0.005s tick.
world = World(stage_units_in_meters=1.0, physics_dt=1.0 / 200.0, rendering_dt=1.0 / 200.0)
world.scene.add_default_ground_plane()

# Must use the IsaacLab-specific USD - same as training; has correct joint order
# and actuator params (G1_MINIMAL_CFG.spawn.usd_path in
# isaaclab_assets/robots/unitree.py).
G1_USD = "https://omniverse-content-production.s3-us-west-2.amazonaws.com/Assets/Isaac/5.1/Isaac/IsaacLab/Robots/Unitree/G1/g1_minimal.usd"
G1_PRIM = "/World/G1"  # top-level reference prim, used for placing the whole asset
add_reference_to_stage(usd_path=G1_USD, prim_path=G1_PRIM)

stage = omni.usd.get_context().get_stage()
prim = stage.GetPrimAtPath(G1_PRIM)
xform = UsdGeom.Xformable(prim)
xform.ClearXformOpOrder()
xform.AddTranslateOp().Set(Gf.Vec3d(0, 0, 0.74))  # matches training init_state z=0.74

# The ArticulationRootAPI in g1_minimal.usd is on the "pelvis" link, not the
# top-level reference prim (confirmed by inspecting the stage directly - unlike
# A1 where "trunk" happened to also be a guessable name, this isn't discoverable
# just by reading configs). If robot.initialize() below fails, re-check with:
#   from pxr import Usd, UsdPhysics
#   for p in Usd.PrimRange(stage.GetPrimAtPath(G1_PRIM)):
#       if p.HasAPI(UsdPhysics.ArticulationRootAPI): print(p.GetPath())
G1_ROOT_PRIM = f"{G1_PRIM}/pelvis"

# ── ROS 2 OmniGraph bridge ─────────────────────────────────────────────────────
og.Controller.edit(
    {"graph_path": "/ActionGraph", "evaluator_name": "execution"},
    {
        og.Controller.Keys.CREATE_NODES: [
            ("OnPlaybackTick",    "omni.graph.action.OnPlaybackTick"),
            ("ROS2Context",       "isaacsim.ros2.bridge.ROS2Context"),
            ("PublishJointState", "isaacsim.ros2.bridge.ROS2PublishJointState"),
            ("SubscribeTwist",    "isaacsim.ros2.bridge.ROS2SubscribeTwist"),
            ("ComputeOdometry",   "isaacsim.core.nodes.IsaacComputeOdometry"),
            ("ReadSimTime",       "isaacsim.core.nodes.IsaacReadSimulationTime"),
            ("PublishOdometry",   "isaacsim.ros2.bridge.ROS2PublishOdometry"),
        ],
        og.Controller.Keys.CONNECT: [
            ("OnPlaybackTick.outputs:tick",        "PublishJointState.inputs:execIn"),
            ("OnPlaybackTick.outputs:tick",        "SubscribeTwist.inputs:execIn"),
            ("OnPlaybackTick.outputs:tick",        "ComputeOdometry.inputs:execIn"),
            ("ROS2Context.outputs:context",        "PublishJointState.inputs:context"),
            ("ROS2Context.outputs:context",        "SubscribeTwist.inputs:context"),
            ("ROS2Context.outputs:context",        "PublishOdometry.inputs:context"),
            ("ComputeOdometry.outputs:execOut",         "PublishOdometry.inputs:execIn"),
            ("ComputeOdometry.outputs:position",        "PublishOdometry.inputs:position"),
            ("ComputeOdometry.outputs:orientation",     "PublishOdometry.inputs:orientation"),
            ("ComputeOdometry.outputs:linearVelocity",  "PublishOdometry.inputs:linearVelocity"),
            ("ComputeOdometry.outputs:angularVelocity", "PublishOdometry.inputs:angularVelocity"),
            ("ReadSimTime.outputs:simulationTime",      "PublishOdometry.inputs:timeStamp"),
        ],
        og.Controller.Keys.SET_VALUES: [
            ("PublishJointState.inputs:targetPrim", [G1_ROOT_PRIM]),
            ("PublishJointState.inputs:topicName",  "joint_states"),
            ("SubscribeTwist.inputs:topicName",     "cmd_vel"),
            ("ComputeOdometry.inputs:chassisPrim",  [usdrt.Sdf.Path(G1_ROOT_PRIM)]),
            ("PublishOdometry.inputs:topicName",    "odom"),
        ],
    },
)

world.reset()

# ── Articulation handle ────────────────────────────────────────────────────────
from isaacsim.core.prims import SingleArticulation
robot = SingleArticulation(prim_path=G1_ROOT_PRIM, name="g1")
try:
    robot.initialize()
except Exception as e:
    raise RuntimeError(
        f"Failed to initialize articulation at {G1_ROOT_PRIM}. See the comment above "
        "G1_ROOT_PRIM for how to re-discover the correct prim path if the USD changes."
    ) from e

# g1_minimal.usd's joints have a NATIVE PhysX drive baked in (stiffness=100 authored in the
# USD, which get_gains() reports as ~5729 after PhysX's internal scaling) - unlike the A1 USD,
# which genuinely ships with zero stiffness. set_joint_efforts() is only valid effort control
# "if there is no joint drive or the stiffness and damping are set to zero" (Isaac Sim docs);
# left active, this native drive fights the manually-computed PD torque below the whole time,
# suppressing most commanded motion (confirmed empirically: disabling it took a single-joint
# effort test from ~0.16 rad of movement to >2 rad for the same applied torque). Explicitly
# switch every joint to effort control (zeroes the native stiffness/damping) so our own PD loop
# has full authority.
robot._articulation_view.switch_control_mode("effort")

try:
    usd_joint_names = list(robot.joint_names)
except AttributeError:
    usd_joint_names = list(robot.dof_names)
print(f"USD joint order ({len(usd_joint_names)} joints):", usd_joint_names)

# ── Per-joint defaults, PD gains, and effort limits ─────────────────────────────
# Matches G1_MINIMAL_CFG's actuator groups ("legs", "feet", "arms") and init_state
# in isaaclab_assets/robots/unitree.py, cross-checked against params/env.yaml for
# this training run and the auto-generated IO descriptor
# (docs/source/_static/policy_deployment/01_io_descriptors/
#  isaac_velocity_flat_g1_v0_IO_descriptors.yaml).
#
# Keyed by exact joint name rather than position: IsaacLab's JointPositionAction
# (joint_names=['.*'], preserve_order=False) and the default joint_pos_rel/
# joint_vel_rel observations all resolve to the asset's native joint order with no
# permutation (see a1_policy_ros2.py's JOINT_NAMES fix for the full explanation of
# why this matters and how it was discovered). So usd_joint_names IS the training
# order already; building these vectors by name keeps this correct even if a
# different G1 USD variant orders joints differently.
#   name: (default_pos [rad], stiffness/KP, damping/KD, effort_limit [N*m])
JOINT_GAINS = {
    "left_hip_pitch_joint":       (-0.20, 200.0, 5.0, 300.0),
    "right_hip_pitch_joint":      (-0.20, 200.0, 5.0, 300.0),
    "torso_joint":                ( 0.0,  200.0, 5.0, 300.0),
    "left_hip_roll_joint":        ( 0.0,  150.0, 5.0, 300.0),
    "right_hip_roll_joint":       ( 0.0,  150.0, 5.0, 300.0),
    "left_shoulder_pitch_joint":  ( 0.35,  40.0, 10.0, 300.0),
    "right_shoulder_pitch_joint": ( 0.35,  40.0, 10.0, 300.0),
    "left_hip_yaw_joint":         ( 0.0,  150.0, 5.0, 300.0),
    "right_hip_yaw_joint":        ( 0.0,  150.0, 5.0, 300.0),
    "left_shoulder_roll_joint":   ( 0.16,  40.0, 10.0, 300.0),
    "right_shoulder_roll_joint":  (-0.16,  40.0, 10.0, 300.0),
    "left_knee_joint":            ( 0.42, 200.0, 5.0, 300.0),
    "right_knee_joint":           ( 0.42, 200.0, 5.0, 300.0),
    "left_shoulder_yaw_joint":    ( 0.0,   40.0, 10.0, 300.0),
    "right_shoulder_yaw_joint":   ( 0.0,   40.0, 10.0, 300.0),
    "left_ankle_pitch_joint":     (-0.23,  20.0, 2.0,  20.0),
    "right_ankle_pitch_joint":    (-0.23,  20.0, 2.0,  20.0),
    "left_elbow_pitch_joint":     ( 0.87,  40.0, 10.0, 300.0),
    "right_elbow_pitch_joint":    ( 0.87,  40.0, 10.0, 300.0),
    "left_ankle_roll_joint":      ( 0.0,   20.0, 2.0,  20.0),
    "right_ankle_roll_joint":     ( 0.0,   20.0, 2.0,  20.0),
    "left_elbow_roll_joint":      ( 0.0,   40.0, 10.0, 300.0),
    "right_elbow_roll_joint":     ( 0.0,   40.0, 10.0, 300.0),
    "left_five_joint":            ( 0.0,   40.0, 10.0, 300.0),
    "left_three_joint":           ( 0.0,   40.0, 10.0, 300.0),
    "left_zero_joint":            ( 0.0,   40.0, 10.0, 300.0),
    "right_five_joint":           ( 0.0,   40.0, 10.0, 300.0),
    "right_three_joint":          ( 0.0,   40.0, 10.0, 300.0),
    "right_zero_joint":           ( 0.0,   40.0, 10.0, 300.0),
    "left_six_joint":             ( 0.0,   40.0, 10.0, 300.0),
    "left_four_joint":            ( 0.0,   40.0, 10.0, 300.0),
    "left_one_joint":             ( 1.0,   40.0, 10.0, 300.0),
    "right_six_joint":            ( 0.0,   40.0, 10.0, 300.0),
    "right_four_joint":           ( 0.0,   40.0, 10.0, 300.0),
    "right_one_joint":            (-1.0,   40.0, 10.0, 300.0),
    "left_two_joint":             ( 0.52,  40.0, 10.0, 300.0),
    "right_two_joint":            (-0.52,  40.0, 10.0, 300.0),
}

missing = [n for n in usd_joint_names if n not in JOINT_GAINS]
if missing:
    raise RuntimeError(f"USD has joints not in JOINT_GAINS (G1 variant mismatch?): {missing}")

NUM_JOINTS = len(usd_joint_names)
DEFAULT_POS = np.array([JOINT_GAINS[n][0] for n in usd_joint_names])
KP_VEC = np.array([JOINT_GAINS[n][1] for n in usd_joint_names])
KD_VEC = np.array([JOINT_GAINS[n][2] for n in usd_joint_names])
EFFORT_LIMIT_VEC = np.array([JOINT_GAINS[n][3] for n in usd_joint_names])

last_action = torch.zeros(NUM_JOINTS)
cmd_vel = [0.0, 0.0, 0.0]  # [vx, vy, yaw_rate]

# ── ROS 2 cmd_vel reader ───────────────────────────────────────────────────────
def get_cmd_vel():
    """Read the latest cmd_vel from the OmniGraph SubscribeTwist node."""
    try:
        linear = og.Controller.get(og.Controller.attribute("/ActionGraph/SubscribeTwist.outputs:linearVelocity"))
        angular_z = og.Controller.get(og.Controller.attribute("/ActionGraph/SubscribeTwist.outputs:angularVelocity"))[2]
        return [float(linear[0]), float(linear[1]), float(angular_z)]
    except Exception:
        return [0.0, 0.0, 0.0]

# ── PD torque control (replicates IsaacLab's per-group ImplicitActuator model) ──
# G1_MINIMAL_CFG's joint drive stiffness/damping in the USD mirror the actuator
# cfg directly (unlike A1's DCMotor-with-zero-USD-stiffness quirk), but
# apply_action(joint_positions=...) still isn't used here: torque must be
# recomputed from fresh joint state and reapplied every physics step (not just
# every policy step), matching how the actuator model actually runs in training.
# Target joint positions, held fixed between policy updates.
target_pos = DEFAULT_POS.copy()

# ── Main loop ──────────────────────────────────────────────────────────────────
world.play()
print("Simulation running. Topics: /joint_states, /odom, /cmd_vel")

step = 0
POLICY_FREQ = 4  # run policy every 4 sim steps (matches decimation=4)

while app.is_running():
    # Apply PD torque every physics step, toward the current held-fixed target.
    joint_pos_raw = robot.get_joint_positions()
    joint_vel_raw = robot.get_joint_velocities()
    if joint_pos_raw is not None and joint_vel_raw is not None:
        effort = KP_VEC * (target_pos - joint_pos_raw) - KD_VEC * joint_vel_raw
        effort = np.clip(effort, -EFFORT_LIMIT_VEC, EFFORT_LIMIT_VEC)
        robot.set_joint_efforts(effort)

    # Only render on the last physics tick of each decimation window (still ~50 fps,
    # matching the control rate) - physics_dt == rendering_dt so this doesn't change
    # how much sim time a step advances, only how often the viewport redraws.
    world.step(render=(step + 1) % POLICY_FREQ == 0)
    step += 1

    if step % POLICY_FREQ != 0:
        continue

    # Read cmd_vel from ROS 2
    cmd = get_cmd_vel()

    # Get robot state
    pos, orient = robot.get_world_pose()
    lin_vel_world = robot.get_linear_velocity()
    ang_vel_world = robot.get_angular_velocity()
    joint_pos_raw = robot.get_joint_positions()
    joint_vel_raw = robot.get_joint_velocities()

    if joint_pos_raw is None or joint_vel_raw is None:
        continue

    # Isaac Sim / Isaac Lab use (w, x, y, z) quaternion convention.
    # scipy.spatial.transform.Rotation.from_quat expects (x, y, z, w).
    quat = orient  # (w, x, y, z) from Isaac Sim
    rot = R.from_quat([quat[1], quat[2], quat[3], quat[0]])  # → (x, y, z, w) for scipy

    # Rotate world-frame velocities to body frame (matches training obs: root_lin_vel_b, root_ang_vel_b)
    lin_vel_body = rot.inv().apply(lin_vel_world)
    ang_vel_body = rot.inv().apply(ang_vel_world)

    # Gravity projected into body frame
    gravity_world = np.array([0.0, 0.0, -1.0])
    projected_gravity = rot.inv().apply(gravity_world)

    # Build observation vector (123 dims: 3+3+3+3+37+37+37, flat env, no height scan)
    obs = np.concatenate([
        lin_vel_body,                         # 3  base_lin_vel (body frame)
        ang_vel_body,                         # 3  base_ang_vel (body frame)
        projected_gravity,                    # 3
        np.array(cmd),                        # 3  velocity_commands
        joint_pos_raw - DEFAULT_POS,           # 37 joint_pos_rel
        joint_vel_raw,                         # 37 joint_vel_rel
        last_action.numpy(),                   # 37 last_action
    ])

    # Run policy (JIT module: obs -> action mean, no extra outputs)
    with torch.no_grad():
        obs_tensor = torch.from_numpy(obs).float().unsqueeze(0)
        action = policy(obs_tensor).squeeze(0)

    last_action = action.clone()

    if step % (POLICY_FREQ * 50) == 0:  # print every ~50 policy steps
        print(f"[step {step}] obs norm: {np.linalg.norm(obs):.3f} | action norm: {action.norm():.3f}")

    # scale=0.5 confirmed in params/env.yaml: scale: 0.5 (A1 used 0.25 - don't copy that over)
    target_pos = DEFAULT_POS + action.numpy() * 0.5

app.close()
